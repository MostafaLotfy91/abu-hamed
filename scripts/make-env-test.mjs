#!/usr/bin/env node
// Writes .env.test for the E2E suite from a LOCAL Supabase stack (`npx supabase start` must be running).
// Refuses anything that isn't localhost, never prints keys, and never touches .env.
//   node scripts/make-env-test.mjs            # create .env.test (keeps an existing one)
//   node scripts/make-env-test.mjs --force    # overwrite
import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const OUT = ".env.test";
if (existsSync(OUT) && !process.argv.includes("--force")) {
  console.error(`${OUT} already exists. Re-run with --force to overwrite.`);
  process.exit(1);
}

let raw;
try {
  raw = execSync("npx supabase status -o env", { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
} catch {
  console.error("Could not read `supabase status`. Start the local stack first: npx supabase start (needs Docker).");
  process.exit(1);
}

const vars = Object.fromEntries(
  raw.split(/\r?\n/).map((l) => /^([A-Z_]+)="?(.*?)"?$/.exec(l.trim())).filter(Boolean).map((m) => [m[1], m[2]]),
);
const api = vars.API_URL;
const anon = vars.ANON_KEY ?? vars.PUBLISHABLE_KEY;
const service = vars.SERVICE_ROLE_KEY ?? vars.SECRET_KEY;
if (!api || !anon || !service) {
  console.error("supabase status did not report API_URL, ANON_KEY and SERVICE_ROLE_KEY.");
  process.exit(1);
}
const host = new URL(api).hostname;
if (!["localhost", "127.0.0.1", "::1"].includes(host)) {
  console.error(`Refusing: API_URL host "${host}" is not local.`);
  process.exit(1);
}

const pw = () => randomBytes(12).toString("base64url");
const lines = [
  "# Generated by scripts/make-env-test.mjs from the LOCAL Supabase stack. Git-ignored. Do not point at production.",
  "E2E_BASE_URL=http://localhost:8080",
  `VITE_SUPABASE_URL=${api}`,
  `VITE_SUPABASE_PUBLISHABLE_KEY=${anon}`,
  `SUPABASE_URL=${api}`,
  `SUPABASE_PUBLISHABLE_KEY=${anon}`,
  `SUPABASE_SERVICE_ROLE_KEY=${service}`,
  `RATE_LIMIT_SALT=${pw()}`,
  "E2E_ADMIN_EMAIL=e2e-admin@example.test",
  `E2E_ADMIN_PASSWORD=${pw()}`,
  "E2E_CUSTOMER_EMAIL=e2e-customer@example.test",
  `E2E_CUSTOMER_PASSWORD=${pw()}`,
  "E2E_DRIVER_EMAIL=e2e-driver@example.test",
  `E2E_DRIVER_PASSWORD=${pw()}`,
  "E2E_WEB_SERVER=1",
  "",
];
writeFileSync(OUT, lines.join("\n"), { mode: 0o600 });
console.log(`Wrote ${OUT} for the local stack at ${api} (keys not shown).`);
